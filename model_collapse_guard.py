    fc_good.add_forecast(
        "gdp_q2_forecast",
        ["measured_gdp_q1", "measured_employment"],
        25.6,
    )
    result = fc_good.analyze()
    print(f"  Max depth: {result['max_depth']}, Grounded: {result['grounded']}")

    print("\n── FORECAST CHAIN: UNGROUNDED ──")
