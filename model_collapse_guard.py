    fc_bad.add_forecast("consensus_forecast",   ["analyst_forecast"])
    fc_bad.add_forecast("market_expectation",   ["consensus_forecast"])
    fc_bad.add_forecast("fed_forward_guidance", ["market_expectation"])
    fc_bad.add_forecast("next_rate_prediction", ["fed_forward_guidance"])
