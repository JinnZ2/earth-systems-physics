"""
model_collapse_guard.py
───────────────────────
Detects conditions that lead to model collapse:

1. Synthetic data feeding back into training
2. Recursive generation without ground-truth anchoring
3. Financial forecast chains referencing only prior forecasts

Integrates conceptually with self_referential_guard.DependencyGraph
for grounding verification (same grounding logic applied to data
provenance instead of variable dependencies).

CC0 — No rights reserved. stdlib only.
"""

import math
from typing import Dict, List, Optional, Tuple, Set


# ═══════════════════════════════════════════════════════════
# LAYER 0: CONTAMINATION TRACKER
# ═══════════════════════════════════════════════════════════

class ContaminationTracker:
    """
    Tracks data provenance across generations.
    Each datum is either:
      - MEASURED:  from physical instrument / direct observation
      - DERIVED:   computed from other data (retains ancestor purity)
      - SYNTHETIC: generated by a model (contaminant)

    Collapse risk = f(synthetic_fraction, max_generation_depth,
                      longest_chain_without_measurement)
    """

    def __init__(self):
        self.sources: Dict[str, Dict] = {}

    def add_measured(self, name: str, instrument: str = ""):
        self.sources[name] = {
            "type": "MEASURED",
            "instrument": instrument,
            "generation": 0,
            "parents": [],
            "synthetic_ancestry": 0.0,
        }

    def add_derived(self, name: str, parents: List[str]):
        if not parents:
            raise ValueError(f"{name}: derived data must have parents")
        missing = [p for p in parents if p not in self.sources]
        if missing:
            raise ValueError(f"{name}: unknown parents {missing}")

        parent_records = [self.sources[p] for p in parents]
        max_gen = max(r["generation"] for r in parent_records)
        avg_synthetic = (
            sum(r["synthetic_ancestry"] for r in parent_records)
            / len(parent_records)
        )

        self.sources[name] = {
            "type": "DERIVED",
            "instrument": None,
            "generation": max_gen + 1,
            "parents": parents,
            "synthetic_ancestry": avg_synthetic,
        }

    def add_synthetic(self, name: str, model_name: str = "",
                      parents: Optional[List[str]] = None):
        parents = parents or []
        if parents:
            parent_records = [
                self.sources[p] for p in parents if p in self.sources
            ]
            max_gen = max(
                (r["generation"] for r in parent_records), default=0
            )
            prior_synthetic = max(
                (r["synthetic_ancestry"] for r in parent_records), default=0.0
            )
        else:
            max_gen = 0
            prior_synthetic = 0.0

        self.sources[name] = {
            "type": "SYNTHETIC",
            "instrument": f"model:{model_name}",
            "generation": max_gen + 1,
            "parents": parents,
            "synthetic_ancestry": min(1.0, (prior_synthetic + 1.0) / 2),
        }

    def collapse_risk(self) -> Dict:
        if not self.sources:
            return {"risk": "NONE", "reason": "No data tracked"}

        total = len(self.sources)
        synthetic_count = sum(
            1 for s in self.sources.values() if s["type"] == "SYNTHETIC"
        )
        synthetic_ratio = synthetic_count / total
        max_generation = max(s["generation"] for s in self.sources.values())
        max_synthetic_ancestry = max(
            s["synthetic_ancestry"] for s in self.sources.values()
        )

        # longest chain with no measurement
        longest_ungrounded = self._longest_ungrounded_chain()

        # risk = worst case across all dimensions
        risks: List[Tuple[str, str]] = []
        if synthetic_ratio > 0.6:
            risks.append((
                "CRITICAL",
                f"Synthetic ratio {synthetic_ratio:.0%} — "
                f"majority of data is model-generated",
            ))
        elif synthetic_ratio > 0.3:
            risks.append((
                "HIGH",
                f"Synthetic ratio {synthetic_ratio:.0%} — "
                f"contamination significant",
            ))
        elif synthetic_ratio > 0.1:
            risks.append((
                "MODERATE",
                f"Synthetic ratio {synthetic_ratio:.0%}",
            ))

        if max_generation > 4:
            risks.append((
                "CRITICAL",
                f"Generation depth {max_generation} — "
                f"deep recursion without anchor",
            ))
        elif max_generation > 2:
            risks.append((
                "HIGH",
                f"Generation depth {max_generation}",
            ))

        if longest_ungrounded > 3:
            risks.append((
                "CRITICAL",
                f"Longest ungrounded chain: {longest_ungrounded} steps",
            ))
        elif longest_ungrounded > 1:
            risks.append((
                "HIGH",
                f"Longest ungrounded chain: {longest_ungrounded} steps",
            ))

        if max_synthetic_ancestry > 0.8:
            risks.append((
                "HIGH",
                f"Max synthetic ancestry: {max_synthetic_ancestry:.0%}",
            ))

        if not risks:
            return {
                "risk": "LOW",
                "reasons": ["Within safe bounds"],
                "synthetic_ratio": round(synthetic_ratio, 3),
                "max_generation": max_generation,
                "recommendation": "Normal operation",
            }

        # worst risk wins
        severity_order = {"CRITICAL": 3, "HIGH": 2, "MODERATE": 1}
        worst = max(risks, key=lambda r: severity_order.get(r[0], 0))

        return {
            "risk": worst[0],
            "reasons": [r[1] for r in risks],
            "synthetic_ratio": round(synthetic_ratio, 3),
            "max_generation": max_generation,
            "longest_ungrounded_chain": longest_ungrounded,
            "max_synthetic_ancestry": round(max_synthetic_ancestry, 3),
            "recommendation": (
                "HALT — AUDIT GROUND TRUTH"
                if worst[0] == "CRITICAL"
                else "AUDIT GROUND TRUTH"
            ),
        }

    def _longest_ungrounded_chain(self) -> int:
        """Walk backwards from each node; count steps to nearest MEASURED."""
        longest = 0
        for name in self.sources:
            depth = self._depth_to_measurement(name, set())
            if depth > longest and depth < 999:
                longest = depth
        return longest

    def _depth_to_measurement(self, name: str, visited: Set[str]) -> int:
        if name in visited:
            return 999  # cycle — treat as ungrounded
        visited.add(name)
        record = self.sources.get(name)
        if not record:
            return 999
        if record["type"] == "MEASURED":
            return 0
        if not record["parents"]:
            return 999 if record["type"] == "SYNTHETIC" else 0
        parent_depths = [
            self._depth_to_measurement(p, visited.copy())
            for p in record["parents"]
        ]
        return min(parent_depths) + 1


