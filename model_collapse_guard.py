    ct.add_synthetic("ai_crop_forecast_v1",       "GPT-4",  ["crop_health_index"])
    ct.add_synthetic("ai_crop_forecast_v2",       "GPT-4",  ["ai_crop_forecast_v1"])
    ct.add_synthetic("ai_crop_forecast_v3",       "GPT-5",  ["ai_crop_forecast_v2"])
    ct.add_synthetic("ai_news_article",           "Claude", ["ai_crop_forecast_v3"])
    ct.add_synthetic("ai_training_data_from_news", "scraper", ["ai_news_article"])

    risk = ct.collapse_risk()
    print(f"  Risk: {risk['risk']}")
    for r in risk.get("reasons", []):
        print(f"    - {r}")
    print(f"  Recommendation: {risk['recommendation']}")

