# LAYER 1: FORECAST CHAIN ANALYZER
# ═══════════════════════════════════════════════════════════

class ForecastChain:
    """
    Models a chain of predictions/forecasts.
    Each link is either:
      - anchored to a measurement
      - referencing another forecast

    Dependency tracking replaces keyword matching for grounding
    analysis.
    """

    def __init__(self):
        self.links: Dict[str, Dict] = {}

    def add_measurement(self, name: str, value: float, unit: str = ""):
        self.links[name] = {
            "type": "MEASUREMENT",
            "value": value,
            "unit": unit,
            "based_on": [],
        }

    def add_forecast(self, name: str, based_on: List[str],
                     value: Optional[float] = None):
        for dep in based_on:
            if dep not in self.links:
                raise ValueError(f"Unknown dependency: {dep}")
        self.links[name] = {
            "type": "FORECAST",
            "value": value,
            "based_on": based_on,
        }

    def analyze(self) -> Dict:
        """Classify the chain: how deep, how grounded."""
        if not self.links:
            return {"depth": 0, "grounded": True, "hazards": []}

        forecasts = {
            k: v for k, v in self.links.items() if v["type"] == "FORECAST"
        }
        measurements = {
            k: v for k, v in self.links.items() if v["type"] == "MEASUREMENT"
        }

        if not forecasts:
            return {
                "total_links": len(self.links),
                "measurements": len(measurements),
                "forecasts": 0,
                "max_depth": 0,
                "grounded": True,
                "hazards": [],
            }

        hazards: List[Dict] = []
        max_depth = 0
        for name in forecasts:
            depth, grounded = self._trace_depth(name, set())
            if depth > max_depth:
                max_depth = depth
            if not grounded:
                hazards.append({
                    "forecast": name,
                    "depth": depth,
                    "warning": (
                        f"'{name}' has no measurement in its ancestry"
                    ),
                })

        return {
            "total_links": len(self.links),
            "measurements": len(measurements),
            "forecasts": len(forecasts),
            "max_depth": max_depth,
            "grounded": len(hazards) == 0,
            "hazards": hazards,
        }

    def _trace_depth(self, name: str, visited: Set[str]) -> Tuple[int, bool]:
        """Returns (depth_to_measurement, is_grounded)."""
        if name in visited:
            return 999, False  # cycle
        visited.add(name)
        link = self.links[name]
        if link["type"] == "MEASUREMENT":
            return 0, True
        if not link["based_on"]:
            return 0, False  # forecast with no basis
        results = [
            self._trace_depth(dep, visited.copy())
            for dep in link["based_on"]
        ]
        min_depth = min(r[0] for r in results)
        any_grounded = any(r[1] for r in results)
        return min_depth + 1, any_grounded


